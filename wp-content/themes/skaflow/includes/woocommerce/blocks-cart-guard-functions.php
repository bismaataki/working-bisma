<?php
/**
 * Keep the block editor off the front end, so the Cart block loads the real cart.
 *
 * WooCommerce's cart data layer decides whether it is rendering inside the editor
 * by asking whether the `core/editor` data store exists:
 *
 *     if ( select( 'core/editor' ) ) { ...return the previewCart fixture... }
 *
 * That store is registered by the `wp-editor` script. Any front-end script that
 * names `wp-editor` in its dependencies therefore convinces the Cart and Mini
 * Cart blocks that they are in the editor: they serve WooCommerce's demo cart
 * (Beanie, Cap, a $1.20 fee, "Free shipping"), never call
 * `/wp-json/wc/store/v1/cart`, and leave the wrapper stuck on `is-loading`.
 *
 * The failure is silent and total — a shopper sees someone else's cart and none
 * of the store's real shipping methods. Observed 2026-08-20 on the blocks cart
 * (#1039902), traced to `verifone-hosted` declaring `wp-editor` in
 * `assets/js/blocks/frontend/blocks.asset.php`. That plugin has since dropped it,
 * but the dependency array is regenerated by the vendor's build, so nothing stops
 * it coming back in the next release — hence a guard rather than a one-off patch.
 *
 * Scoped to scripts that register themselves with WooCommerce Blocks (they depend
 * on `wc-settings` or `wc-blocks-registry`). Such a script has no legitimate use
 * for the editor bundle, so stripping it is safe. Front-end editors belonging to
 * unrelated plugins are left alone.
 *
 * @package Skaflow
 */

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

add_action( 'wp_print_scripts', 'skaflow_strip_editor_deps_from_blocks_scripts', 0 );
add_action( 'wp_print_footer_scripts', 'skaflow_strip_editor_deps_from_blocks_scripts', 0 );

/**
 * Removes editor dependencies from queued WooCommerce Blocks integration scripts.
 *
 * Runs immediately before scripts print, because dependencies are resolved at
 * print time — anything earlier races the payment method registry, which
 * registers its handles while the Cart block renders.
 *
 * @return void
 */
function skaflow_strip_editor_deps_from_blocks_scripts() {
	if ( is_admin() ) {
		return;
	}

	$editor_deps = array( 'wp-editor', 'wp-block-editor' );
	$blocks_deps = array( 'wc-settings', 'wc-blocks-registry' );
	$scripts     = wp_scripts();

	$pending = $scripts->queue;
	$seen    = array();

	while ( $pending ) {
		$handle = array_pop( $pending );

		if ( isset( $seen[ $handle ] ) || ! isset( $scripts->registered[ $handle ] ) ) {
			continue;
		}

		$seen[ $handle ] = true;
		$script          = $scripts->registered[ $handle ];

		if ( array_intersect( $blocks_deps, $script->deps ) ) {
			$script->deps = array_values( array_diff( $script->deps, $editor_deps ) );
		}

		$pending = array_merge( $pending, $script->deps );
	}
}
